package fr.forumhfr.redface2.core.database.migrations

import android.content.Context
import androidx.room.Room
import androidx.room.testing.MigrationTestHelper
import androidx.sqlite.db.SupportSQLiteDatabase
import androidx.sqlite.db.framework.FrameworkSQLiteOpenHelperFactory
import androidx.test.core.app.ApplicationProvider
import androidx.test.platform.app.InstrumentationRegistry
import fr.forumhfr.redface2.core.database.RedfaceDatabase
import fr.forumhfr.redface2.core.database.entities.EditorDraftEntity
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/** #1553: fixtures come from exported schemas; schema 21 is generated by KSP, never hand-written. */
@RunWith(RobolectricTestRunner::class)
@Config(manifest = Config.NONE, sdk = [33])
class EditorDraftQuoteMigrationTest {
    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        RedfaceDatabase::class.java.canonicalName,
        FrameworkSQLiteOpenHelperFactory(),
    )

    @Test
    fun `20 to 21 preserves every old field for ordinary and all attempt states`() = runTest {
        val name = "draft-quotes-20-to-21.db"
        val expected = createVersion20(name)
        helper.runMigrationsAndValidate(name, 21, true, MIGRATION_20_21).use { migrated ->
            migrated.assertNullableRequestColumn()
        }
        val database = Room.databaseBuilder(context(), RedfaceDatabase::class.java, name).build()
        try {
            for (row in expected) assertEquals(row, database.editorDraftDao().get(row.draftKey))
        } finally {
            database.close()
        }
    }

    @Test
    fun `Room really opens and migrates a version 20 database without destructive fallback`() = runTest {
        val name = "draft-quotes-room-open.db"
        val expected = createVersion20(name)
        val database = Room.databaseBuilder(context(), RedfaceDatabase::class.java, name)
            .addMigrations(MIGRATION_20_21).build()
        try {
            for (row in expected) assertEquals(row, database.editorDraftDao().get(row.draftKey))
            assertEquals(21, database.openHelper.readableDatabase.version)
        } finally {
            database.close()
        }
    }

    @Test
    fun `old version 11 draft follows the whole remaining chain to 21`() = runTest {
        val name = "draft-quotes-11-to-21.db"
        helper.createDatabase(name, 11).use { old ->
            old.execSQL(
                """
                INSERT INTO editor_drafts (draftKey, ownerId, body, subject, recipients, updatedAt, isPrivate)
                VALUES ('alice|mpnew', 'alice', 'old body', 'old subject', 'bob', 1234, 1)
                """.trimIndent(),
            )
        }
        helper.runMigrationsAndValidate(
            name, 21, true, MIGRATION_11_12, MIGRATION_12_13, MIGRATION_13_14, MIGRATION_14_15,
            MIGRATION_15_16, MIGRATION_16_17, MIGRATION_17_18, MIGRATION_18_19, MIGRATION_19_20, MIGRATION_20_21,
        ).close()
        val database = Room.databaseBuilder(context(), RedfaceDatabase::class.java, name).build()
        try {
            val row = checkNotNull(database.editorDraftDao().get("alice|mpnew"))
            assertEquals(EditorDraftEntity("alice|mpnew", "alice", "old body", "old subject", "bob", 1234, true), row)
            assertNull(row.pendingInlineQuoteRequest)
        } finally {
            database.close()
        }
    }

    private fun SupportSQLiteDatabase.assertNullableRequestColumn() {
        query("PRAGMA table_info(editor_drafts)").use { columns ->
            var found = false
            while (columns.moveToNext()) {
                if (columns.getString(columns.getColumnIndexOrThrow("name")) == "pendingInlineQuoteRequest") {
                    found = true
                    assertEquals("TEXT", columns.getString(columns.getColumnIndexOrThrow("type")))
                    assertEquals(0, columns.getInt(columns.getColumnIndexOrThrow("notnull")))
                    assertTrue(columns.isNull(columns.getColumnIndexOrThrow("dflt_value")))
                }
            }
            assertTrue(found)
        }
    }

    private fun createVersion20(name: String): List<EditorDraftEntity> {
        val rows = listOf(null, "IN_PROGRESS", "UNCERTAIN", "PUBLISHED").mapIndexed { index, state ->
            EditorDraftEntity(
                draftKey = "alice|reply:23:${index + 1}", ownerId = "alice", body = "body $index",
                subject = "subject $index", recipients = "recipient $index", updatedAt = 1234L + index,
                isPrivate = index % 2 == 0, contentVersion = 7L + index,
                attemptId = state?.let { "attempt-$index" }, attemptVersion = state?.let { 4L + index },
                attemptState = state,
            )
        }
        helper.createDatabase(name, 20).use { old ->
            for (row in rows) {
                old.execSQL(
                    """
                    INSERT INTO editor_drafts (draftKey, ownerId, body, subject, recipients, updatedAt,
                        isPrivate, contentVersion, attemptId, attemptVersion, attemptState)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """.trimIndent(),
                    arrayOf<Any?>(
                        row.draftKey, row.ownerId, row.body, row.subject, row.recipients, row.updatedAt,
                        if (row.isPrivate) 1 else 0, row.contentVersion,
                        row.attemptId, row.attemptVersion, row.attemptState,
                    ),
                )
            }
        }
        return rows
    }

    private fun context(): Context = ApplicationProvider.getApplicationContext()
}
