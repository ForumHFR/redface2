/** R6 references are deliberately recorded on the reference box, never generated by this source edit. */
@OptIn(ExperimentalTestApi::class)
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34], qualifiers = "fr-rFR-w800dp-h480dp-xxhdpi")
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class EditorShortcutRoborazziTest {
    @get:Rule val compose = createComposeRule()
    private var host by mutableStateOf(EditorActionBarFixture())
    private data class Variant(val dark: Boolean, val scale: Float)
    private val variants = listOf(false, true).flatMap { dark ->
        listOf(1f, 1.3f).map { scale -> Variant(dark, scale) }
    }
    private val choices = listOf(EditorShortcut.BOLD, EditorShortcut.ITALIC, EditorShortcut.QUOTE,
        EditorShortcut.LINK, EditorShortcut.RED, EditorShortcut.BLUE, EditorShortcut.GREEN,
        EditorShortcut.ORANGE, EditorShortcut.GREY, EditorShortcut.UPLOAD_IMAGE,
        EditorShortcut.IMAGE_URL, EditorShortcut.IMAGE_SELECTION, EditorShortcut.SEARCH_SMILEYS,
        EditorShortcut.PERSONAL_SMILEY)

    @Test fun `shortcut glyphs in both themes scales narrow portrait and compact heights`() {
        compose.setContent { key(host) { host.Content(showBody = false) } }
        variants.forEach { variant ->
            listOf(360.dp to false, 760.dp to true).forEach { (width, compact) ->
                choices.forEach { choice ->
                    configure(choice, variant, width, compact)
                    shortcut(choice).assertIsDisplayed()
                    capture("${choice.id}_${variant.dark}_${variant.scale}_${width.value}_$compact")
                }
            }
        }
    }

    @Test fun `narrow compact row at rest and representative shortcuts revealed by scrolling`() {
        compose.setContent { key(host) { host.Content(showBody = false) } }
        variants.forEach { variant ->
            configure(EditorShortcut.BOLD, variant, compact = true)
            capture("rest_${variant.dark}_${variant.scale}_360.0_true")
            listOf(EditorShortcut.BOLD, EditorShortcut.BLUE, EditorShortcut.IMAGE_SELECTION).forEach { choice ->
                configure(choice, variant, compact = true)
                scrollToShortcutAndCheckBounds(choice)
                capture("${choice.id}_scrolled_${variant.dark}_${variant.scale}_360.0_true")
            }
        }
    }

    @Test fun `shortcut disabled during upload and hidden in Format in both themes and scales`() {
        compose.setContent { key(host) { host.Content(showBody = false) } }
        variants.forEach { variant ->
            configure(EditorShortcut.UPLOAD_IMAGE, variant)
            compose.runOnIdle {
                host.uploading.value = true
                host.progress.value = UploadProgress(1, 3)
            }
            shortcut(EditorShortcut.UPLOAD_IMAGE).assertIsDisplayed().assertIsNotEnabled()
            capture("upload_disabled_${variant.dark}_${variant.scale}")

            configure(EditorShortcut.PERSONAL_SMILEY, variant)
            shortcut(EditorShortcut.PERSONAL_SMILEY).assertIsDisplayed()
            compose.onNodeWithContentDescription("Mise en forme").performClick()
            shortcut(EditorShortcut.PERSONAL_SMILEY).assertDoesNotExist()
            shortcut(EditorShortcut.BOLD).assertIsDisplayed()
            capture("hidden_format_${variant.dark}_${variant.scale}")
        }
    }

    private fun configure(choice: EditorShortcut, variant: Variant, width: Dp = 360.dp, compact: Boolean = false) {
        compose.runOnIdle {
            host = EditorActionBarFixture().apply {
                dark.value = variant.dark; scale.value = variant.scale; this.width.value = width
                this.compact.value = compact; header.value = true
                firstStatus.value = EditorAppBarStatus(R.drawable.ic_editor_quote, "12 citations", {}, 12)
                secondStatus.value = EditorAppBarStatus(R.drawable.ic_ms_restore_page, "Brouillon retrouvé", {})
                val mp = choice == EditorShortcut.IMAGE_SELECTION
                imageUrl.value = !mp
                val surface = if (mp) EditorShortcutSurface.PRIVATE_MESSAGE_REPLY else EditorShortcutSurface.POST
                shortcut.value = EditorBarShortcut(choice, surface)
            }
        }
    }

    private fun shortcut(choice: EditorShortcut) = compose.onNodeWithContentDescription(
        RuntimeEnvironment.getApplication().getString(editorShortcutCatalog.single { it.choice == choice }.labelRes))

    private fun scrollToShortcutAndCheckBounds(choice: EditorShortcut) {
        val target = shortcut(choice).performScrollTo()
        val row = compose.onNode(hasScrollAction() and hasAnyAncestor(hasTestTag("editor-bar-scroll")))
        // ScrollBy may consume only part of the request; settle and re-measure after each adjustment.
        for (attempt in 0..10) {
            val node = row.fetchSemanticsNode()
            val range = node.config[SemanticsProperties.HorizontalScrollAxisRange]
            val viewport = compose.onNodeWithTag("editor-bar-scroll").getUnclippedBoundsInRoot()
            val icon = target.getUnclippedBoundsInRoot()
            // Unclipped 40 dp state layer, centred in its 48 dp slot; touch bounds can themselves be clipped.
            val horizontalPadding = (EditorChromeMetrics.minimumTargetSize - (icon.right - icon.left)) / 2
            val verticalPadding = (EditorChromeMetrics.minimumTargetSize - (icon.bottom - icon.top)) / 2
            // ED-25 permits a 48 dp viewport: below slot + both fades, require only the full slot to fit.
            val canClearFades = viewport.right - viewport.left >= EditorChromeMetrics.minimumTargetSize + 24.dp
            val leftFade = if (canClearFades && range.value() > 0f) 12.dp else 0.dp
            val rightFade = if (canClearFades && range.value() < range.maxValue()) 12.dp else 0.dp
            val overflow = when {
                icon.left - horizontalPadding < viewport.left + leftFade ->
                    icon.left - horizontalPadding - (viewport.left + leftFade)
                icon.right + horizontalPadding > viewport.right - rightFade ->
                    icon.right + horizontalPadding - (viewport.right - rightFade)
                else -> 0.dp
            }
            if (overflow == 0.dp || attempt == 10) {
                target.assertIsDisplayed()
                assertTrue(
                    "Shortcut must clear the left fade",
                    icon.left - horizontalPadding >= viewport.left + leftFade,
                )
                assertTrue(
                    "Shortcut must clear the right fade",
                    icon.right + horizontalPadding <= viewport.right - rightFade,
                )
                assertTrue("Shortcut must fit below the top edge", icon.top - verticalPadding >= viewport.top)
                assertTrue("Shortcut must fit above the bottom edge", icon.bottom + verticalPadding <= viewport.bottom)
                return
            }
            val delta = with(node.layoutInfo.density) { overflow.toPx() }
            row.performSemanticsAction(SemanticsActions.ScrollBy) { it(delta, 0f) }
            compose.waitForIdle()
        }
    }

    private fun capture(sample: String) {
        compose.onNodeWithTag("bar").captureRoboImage("src/test/screenshots/editor_shortcut_$sample.png")
    }
}
